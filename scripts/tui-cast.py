# --- the recording ---------------------------------------------------------

COLS = 112
# Rows are per-cast: the TUI is a full-screen application and wants a screen,
# while the write-up cast is a transcript that only ever has a dozen lines live
# at once — given 24 it plays out in a window two thirds empty.
ROWS, SHELL_ROWS = 24, 18

# One investigation — the same one docs/demo.md walks through in prose: every
# log, then only the ERROR ones, then who calls whom, then the trace under the
# failure. Each entry is (keys, seconds to wait after them); the waits are what
# make the pty deliver one keystroke per redraw instead of one burst.
KEYS: list[tuple[str, float]] = (
    [("", 1.5)]
    + [(c, 0.10) for c in "/severity_text=ERROR"]
    + [("\r", 1.6), ("m", 1.6), ("q", 0.8), ("t", 2.0), ("q", 0.6), ("q", 0.6)]
)

# The scenes, in the order they play, and how long each is held in milliseconds.
# "typing" expands to one scene per keystroke.
SCENES: list[tuple[str, int]] = [
    ("the unfiltered log list", 1800),
    ("typing", 90),
    ("the ERROR rows", 2800),
    ("the service map", 2800),
    ("the trace waterfall", 4200),
]

ROOT = pathlib.Path(__file__).resolve().parent.parent
BIN = ROOT / "target" / "release" / "mira"


def record(argv: list[str], script, env=None, cwd=None, rows: int = ROWS) -> tuple[bytes, list[int]]:
    """Run `argv` on a pty of our own, type `script` at it, return all it wrote.

    `script` is a list of (keys, seconds to wait after them). The waits are what
    make the pty deliver one keystroke per redraw instead of one burst. The
    second return is the length of the capture after each step, which is the
    only way a scrolling transcript can be cut back into frames — a repainting
    TUI has `ESC[H` to cut on and a shell session has nothing.

    A pty rather than `script(1)`: it takes the window size from the terminal it
    inherits, and there is no terminal here — stdin is the keystroke feeder and
    stdout is a file — so it silently records 80x24 and every capture comes out
    truncated at the right edge. Opening the pty directly is the only way to
    state the size, and it puts the keystroke timing in this process rather than
    in a shell full of `sleep`.
    """
    master, slave = pty.openpty()
    fcntl.ioctl(slave, termios.TIOCSWINSZ, struct.pack("HHHH", rows, COLS, 0, 0))

    def own_the_tty() -> None:  # the child's controlling terminal, so raw mode takes
        os.setsid()
        fcntl.ioctl(0, termios.TIOCSCTTY, 0)

    child = subprocess.Popen(
        argv, stdin=slave, stdout=slave, stderr=subprocess.STDOUT,
        preexec_fn=own_the_tty, close_fds=True, env=env, cwd=cwd,
    )
    os.close(slave)
    out, marks = bytearray(), []

    def drain(seconds: float) -> None:
        end = time.monotonic() + seconds
        while (left := end - time.monotonic()) > 0:
            if not select.select([master], [], [], left)[0]:
                return
            try:
                chunk = os.read(master, 1 << 16)
            except OSError:
                return
            if not chunk:
                return
            out.extend(chunk)

    try:
        for keys, pause in script:
            if keys:
                os.write(master, keys.encode())
            drain(pause)
            marks.append(len(out))
    finally:
        drain(0.5)
        os.close(master)
        if child.poll() is None:
            child.kill()
        child.wait()
    return bytes(out), marks


# --- the parser ------------------------------------------------------------

CSI = re.compile(r"\x1b\[([0-9;?]*)([A-Za-z])")

# The TUI's entire vocabulary. Anything outside it means the reader below has
# stopped being a safe substitute for a terminal emulator.
KNOWN_CSI = {("", "H"), ("", "K"), ("", "J"), ("2", "J"), ("?25", "l"),
             ("?25", "h"), ("?1049", "h"), ("?1049", "l")}
# 36/37/39/90 arrive from `jq`, which colours its output because the other end
# of the pty is a real tty — so the JSON in the write-up cast is syntax-coloured
# by jq itself rather than by anything here. 39 is "back to the default
# foreground", which is not the same as 0 and must not reset bold with it.
KNOWN_SGR = {"0", "1", "2", "7", "31", "32", "33", "34", "35", "36", "37", "39", "90"}

# A cell's style: (colour key, bold, dim, reverse). None is "the default fg".
DEFAULT = (None, False, False, False)


def assert_simple(text: str) -> None:
    for params, final in CSI.findall(text):
        if final == "m":
            unknown = set(params.split(";")) - KNOWN_SGR - {""}
            if unknown:
                sys.exit(f"tui-cast: unhandled SGR {sorted(unknown)}; add it to SGR_FG.")
        elif (params, final) not in KNOWN_CSI:
            sys.exit(
                f"tui-cast: the TUI now emits ESC[{params}{final}, which this reader "
                "cannot place. It assumes a full repaint from home with no cursor "
                "addressing, and that assumption is gone."
            )


def sgr(style, params: str):
    colour, bold, dim, rev = style
    for p in (params or "0").split(";"):
        p = p or "0"
        if p == "0":
            colour, bold, dim, rev = DEFAULT
        elif p == "1":
            bold = True
        elif p == "2":
            dim = True
        elif p == "7":
            rev = True
        elif p == "39":
            colour = None
        else:
            colour = p
    return (colour, bold, dim, rev)


BLANK = [(" ", DEFAULT)] * COLS


def cells_of(line: str, style):
    """One line of output as (char, style) cells, plus the style it ends in."""
    cells, i = [], 0
    while i < len(line):
        m = CSI.match(line, i)
        if m:
            if m.group(2) == "m":
                style = sgr(style, m.group(1))
            i = m.end()
            continue
        if line[i] not in "\r\n":
            cells.append((line[i], style))
        i += 1
    return cells, style


def frames(capture: bytes) -> list[list[list[tuple[str, tuple]]]]:
    """Split the capture into frames, each a ROWS x COLS grid of (char, style)."""
    text = capture.decode("utf-8", "replace")
    assert_simple(text)
    out = []
    for chunk in text.split("\x1b[H")[1:]:
        grid = []
        for line in chunk.split("\r\n"):
            cells, _ = cells_of(line, DEFAULT)
            grid.append((cells + BLANK)[:COLS])
        out.append((grid + [BLANK] * ROWS)[:ROWS])
    return out


def text_of(grid, r: int) -> str:
    return "".join(c for c, _ in grid[r]).rstrip()


def pick(all_frames) -> list[tuple[list, int]]:
    """Turn SCENES into (grid, hold-ms), matched on what the TUI says it is."""
    def footer(f):  # the keymap line: the last row with anything on it
        return next((text_of(f, r) for r in range(ROWS - 1, -1, -1) if text_of(f, r)), "")

    def mid_flight(f):  # a frame still showing the last screen's numbers
        rows = [text_of(f, r) for r in range(ROWS) if text_of(f, r)]
        return len(rows) < 2 or rows[-2].lstrip().startswith(("running", "loading"))

    settled = [f for f in all_frames if not mid_flight(f)]
    editing = [f for f in settled if text_of(f, 1).startswith(" filter> ")]
    resting = [f for f in settled if not text_of(f, 1).startswith(" filter> ")]
    body = lambda f: "\n".join(text_of(f, r) for r in range(ROWS))

    def one(name, test, pool):
        hits = [f for f in pool if test(f)]
        if not hits:
            sys.exit(f"tui-cast: no captured frame is {name}. The keymap or the footers moved.")
        # The first settled match, not the last: the screen comes back more than
        # once (backing out of the trace redraws the log list), and only the
        # first arrival still carries its own query's numbers in the footer.
        return hits[0]

    picked = []
    for name, hold in SCENES:
        if name == "typing":
            seen = set()
            for f in editing:
                if (key := text_of(f, 1)) not in seen:
                    seen.add(key)
                    picked.append((f, hold))
        elif name == "the unfiltered log list":
            picked.append((one(name, lambda f: "(none)" in text_of(f, 1), resting), hold))
        elif name == "the ERROR rows":
            picked.append((one(name, lambda f: "ERROR" in text_of(f, 2)
                               and "t trace" in footer(f), resting), hold))
        elif name == "the service map":
            picked.append((one(name, lambda f: "filter on this service" in footer(f), resting), hold))
        elif name == "the trace waterfall":
            picked.append((one(name, lambda f: "span" in footer(f) and "trace " in body(f),
                               resting), hold))
        else:
            sys.exit(f"tui-cast: SCENES names {name!r} and pick() does not know it.")
    return picked


