#!/usr/bin/env python3
"""Record Mira driving a real investigation, and write it out as a GIF.

    make demo                            # in another terminal, or --addr any node
    python3 scripts/tui-cast.py investigation
    python3 scripts/tui-cast.py write-up

Two casts, because the story has two halves on two surfaces. `investigation` is
`mira mira`: every log, then only the ERROR ones, then who calls whom, then the
trace under the failure. `write-up` is `POST /mcp` in a shell, where `render_rca`
refuses a citation it cannot re-prove and then writes the document.

Both are recordings, not mock-ups. Every character came out of a real Mira over
the demo generator's data, and every number in them — the query plans, the record
count beside each claim — is that run's own. The only thing invented is the dwell
between frames, because a pty capture carries no clock.

Three steps, and the middle one is the only surprising one:

1.  Drive the thing on a pty of our own, with a pause after each step so it sees
    a person rather than a paste, and keep the capture length after each one.
2.  Read the capture with fifty lines rather than a terminal emulator. What both
    casts write is unusually easy: the TUI repaints from the top-left every frame
    with no cursor addressing at all, a shell only ever appends, and between them
    the vocabulary is `ESC[H`, `ESC[K`, `ESC[J` and a dozen SGR codes.
    `assert_simple` fails the run the moment that stops being true, which is the
    moment this shortcut needs replacing with a real emulator. The two differ
    only in where the frame boundaries are: `ESC[H` for a repaint, the recorder's
    byte offsets for a transcript that scrolls.
3.  Draw the cell grid with Pillow and save the frames as one GIF. GIF stores
    each frame as the rectangle that changed, so the twenty frames of typing in
    `investigation` — one row different each — cost almost nothing.

Requires Pillow and a monospaced TTF; both are on the machine that regenerates
the assets, neither is a dependency of Mira. Nothing in CI runs this — the GIFs
are committed, and regenerated by hand when what they show changes. Look at the
result: a layout that has lost content still renders perfectly well.

ponytail: `investigation` matches its scenes on what the TUI writes in its own
footer rather than on frame numbers, so a reworded keymap fails loudly here
instead of quietly picking the wrong screen. If the footers change, fix SCENES.
"""

