# (command, seconds to wait for its output, milliseconds to hold the frame it
# leaves). A step that holds 0 leaves no frame — the two function definitions
# and the `sed` are setup a reader reads in place, not beats to pause on.
#
# Every line is under 112 columns on purpose: a wrapped command is a command a
# reader has to reassemble. `rca` and `q` exist so the four calls after them are
# short enough to read, and are defined in the open rather than hidden in a
# fixture, because the URL they post to is half of what is being shown.
def shell_steps(addr: str) -> list[tuple[str, float, int]]:
    return [
        # Nothing, first: the shell has not printed its prompt yet when the
        # recorder starts writing, and without this the tty echoes the first
        # command above the prompt that is supposed to introduce it.
        ("", 0.8, 0),
        ("# an agent has finished investigating. three claims it wants to publish:", 0.4, 0),
        ("jq -r '.params.arguments.evidence[].claim' findings.json", 1.0, 2200),
        ("", 0.3, 0),
        ("# render_rca re-runs every one of them before it writes a word.", 0.4, 0),
        (f"rca() {{ curl -s {addr}/mcp -d @\"$1\" | jq -r '.result.content[0].text'; }}", 0.5, 0),
        ("rca findings.json", 2.0, 4800),
        ("", 0.3, 0),
        ("sed s/CardExpired/CardDeclined/ findings.json > fixed.json   # the agent corrects it",
         0.6, 0),
        # No hold of its own: the line count is worth seeing, but it is still on
        # screen in the next frame and a whole beat for `59 write-up.md` is a
        # beat the reader spends not reading the evidence.
        ("rca fixed.json > write-up.md; wc -l write-up.md", 2.5, 0),
        ("grep -A4 '## Evidence' write-up.md", 1.2, 5400),
        ("", 0.3, 0),
        ("# `emit: true` stored the write-up itself. there is no incident store:", 0.4, 0),
        (f"q() {{ curl -s {addr}/api/v1/query -d \"$1\" | jq -c .stats; }}", 0.5, 0),
        ("""q '{"signal":"logs","where":[{"field":"event_name","eq":"rca"}],"limit":1}'""",
         1.5, 5000),
    ]


def record_shell(addr: str, tmp: pathlib.Path) -> tuple[bytes, list[int], list[int]]:
    """Drive a real `sh` through the session above, in a scratch directory."""
    (tmp / "findings.json").write_text(json.dumps(FINDINGS, indent=1))
    steps = shell_steps(addr)
    # A prompt of our own, in the brand colour, and nothing else: the recording
    # must not carry whoever's dotfiles are on the machine that made it. SGR 35
    # is magenta, which the TUI never emits and SGR_FG maps to rust — the same
    # licence the rest of that table takes, where "31 is red" and which red is
    # the terminal's business.
    env = {"PS1": "\x1b[35m$\x1b[0m ", "PS2": "> ", "TERM": "dumb", "HOME": str(tmp),
           "PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LANG": "en_US.UTF-8"}
    capture, marks = record(
        ["/bin/sh"], [(cmd + "\r" if cmd else "", wait) for cmd, wait, _ in steps],
        env=env, cwd=tmp, rows=SHELL_ROWS,
    )
    return capture, marks, [hold for _, _, hold in steps]


def scrollback(capture: bytes, marks: list[int], holds: list[int], rows: int):
    """Cut a scrolling transcript into frames: the last ROWS lines at each mark.

    A shell does not repaint, so there is no `ESC[H` to split on — the frame at
    step n is everything written up to `marks[n]`, wrapped at the window width
    and shown from the bottom. Which is what the terminal on the other end of
    the pty was displaying at that moment, since it was doing the same sum.
    """
    text = capture.decode("utf-8", "replace").replace("\r\n", "\n").replace("\r", "")
    assert_simple(text)
    out = []
    for end, hold in zip(marks, holds):
        if not hold:
            continue
        lines, style = [], DEFAULT
        # The byte offset is into the capture; decoding a prefix of it can split
        # a multi-byte character, so cut the decoded text at the same *character*
        # count instead — `errors="replace"` keeps the two in step.
        for line in capture[:end].decode("utf-8", "replace").replace("\r\n", "\n") \
                                 .replace("\r", "").split("\n"):
            cells, style = cells_of(line, style)
            # Soft-wrap, exactly as the terminal does. A wrapped line is one the
            # reader can still read; a truncated one is a silent lie.
            for i in range(0, max(len(cells), 1), COLS):
                lines.append((cells[i:i + COLS] + BLANK)[:COLS])
        out.append(((lines[-rows:] + [BLANK] * rows)[:rows], hold))
    return out


# --- the drawing -----------------------------------------------------------

# A capture carries no colours of its own: SGR 31 is "red", and which red is the
# terminal's business. These are a choice made once — the docs site's own
# surface from stylesheets/extra.css, and GitHub-dark's ANSI over it, so a
# reader who has seen the web UI recognises the palette.
BG, FG, DIM, BRIGHT = "#0d1117", "#c9d1d9", "#6e7681", "#f0f6fc"
SGR_FG = {"31": "#ff7b72", "32": "#3fb950", "33": "#d29922", "34": "#58a6ff",
          # 35 is the shell prompt in the write-up cast and nothing else; the
          # TUI never emits it. See record_shell.
          "35": "#f74c00", "36": "#39c5cf", "37": "#b1bac4", "90": DIM}
RUST = "#f74c00"

# Menlo's advance is exactly 0.6em, so at 15px a cell is 9px wide with no
# rounding drift down a 112-column row. Change the size and check that
# `font.getlength("M")` is still an integer, or runs will walk off the grid.
FONT_SIZE = 15
CELL_W, CELL_H = 9, 20
PAD = 14
EDGE = 2  # the square two-pixel edge every panel on the docs site has
FONT_PATHS = ["/System/Library/Fonts/Menlo.ttc", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
              "/Library/Fonts/DejaVuSansMono.ttf"]

WIDTH = PAD * 2 + COLS * CELL_W


def height_of(grid) -> int:
    return PAD * 2 + len(grid) * CELL_H


def load_font(bold: bool):
    for p in FONT_PATHS:
        if os.path.exists(p):
            # Menlo.ttc carries Regular at index 0 and Bold at 1; a plain .ttf
            # ignores the index and renders bold as regular, which is fine —
            # the TUI only ever uses bold on its own title.
            font = ImageFont.truetype(p, FONT_SIZE, index=1 if bold and p.endswith(".ttc") else 0)
            if font.getlength("M") != CELL_W:
                sys.exit(f"tui-cast: {p} advances {font.getlength('M')}px at {FONT_SIZE}px, "
                         f"not the {CELL_W}px the grid assumes.")
            return font
    sys.exit(f"tui-cast: no monospaced font found. Looked in: {', '.join(FONT_PATHS)}")


def colour_of(style) -> str:
    key, bold, dim, _ = style
    if key in SGR_FG:
        return SGR_FG[key]
    return DIM if dim else (BRIGHT if bold else FG)


def runs(cells):
    """Group a row into (column, text, style), dropping trailing blank space."""
    out, start, buf, cur = [], 0, [], None
    for i, (ch, st) in enumerate(cells):
        if st != cur:
            if buf:
                out.append((start, "".join(buf), cur))
            start, buf, cur = i, [], st
        buf.append(ch)
    if buf:
        out.append((start, "".join(buf), cur))
    return [(c, t, s) for c, t, s in out if t.strip() or s[3]]


def render(grid, fonts) -> Image.Image:
    h = height_of(grid)
    im = Image.new("RGB", (WIDTH, h), BG)
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, WIDTH - 1, h - 1], outline=RUST, width=EDGE)
    for r, cells in enumerate(grid):
        y = PAD + r * CELL_H
        for col, text, style in runs(cells):
            x = PAD + col * CELL_W
            fill = colour_of(style)
            if style[3]:  # reverse video: the run's colour becomes its background
                d.rectangle([x, y, x + len(text) * CELL_W - 1, y + CELL_H - 1], fill=fill)
                fill = BG
            if text.strip():
                d.text((x, y + 2), text, font=fonts[style[1]], fill=fill)
    return im


def to_gif(scenes, out: pathlib.Path) -> None:
    fonts = {False: load_font(False), True: load_font(True)}
    images = [render(grid, fonts) for grid, _ in scenes]
    # One palette for the whole animation, taken from the frames stacked into a
    # single image: quantising each frame on its own gives each a different
    # palette, which defeats GIF's own frame-to-frame delta and triples the file.
    # No dithering — dither noise on a flat terminal background is pure entropy.
    h = images[0].height
    stack = Image.new("RGB", (WIDTH, h * len(images)))
    for i, im in enumerate(images):
        stack.paste(im, (0, i * h))
    palette = stack.convert("P", palette=Image.Palette.ADAPTIVE, colors=64)
    quantised = [im.quantize(palette=palette, dither=Image.Dither.NONE) for im in images]
    quantised[0].save(
        out, save_all=True, append_images=quantised[1:], loop=0,
        duration=[hold for _, hold in scenes], disposal=1, optimize=True,
    )


CASTS = {"investigation": "the terminal UI, from every log to the trace under the failure",
         "write-up": "render_rca refusing a citation it cannot re-prove, then writing"}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cast", nargs="?", default="investigation", choices=sorted(CASTS),
                    help="; ".join(f"{k}: {v}" for k, v in CASTS.items()))
    ap.add_argument("--addr", default="localhost:4318", help="a node to read; `make demo` starts one")
    ap.add_argument("--raw", type=pathlib.Path,
                    help="replay a capture instead of recording (investigation only)")
    ap.add_argument("--keep-raw", type=pathlib.Path, help="write the pty capture here too")
    ap.add_argument("--out", type=pathlib.Path, help="default: docs/assets/tui/<cast>.gif")
    args = ap.parse_args()
    out = args.out or ROOT / f"docs/assets/tui/{args.cast}.gif"

    if args.cast == "write-up":
        if args.raw:
            # The frames are cut on byte offsets the recorder returns, and a raw
            # file does not carry them. Replay is an investigation-only luxury.
            sys.exit("tui-cast: --raw cannot replay the write-up cast; it needs the marks.")
        with tempfile.TemporaryDirectory(prefix="tui-cast-") as tmp:
            capture, marks, holds = record_shell(args.addr, pathlib.Path(tmp))
        scenes = scrollback(capture, marks, holds, SHELL_ROWS)
    else:
        if args.raw:
            capture = args.raw.read_bytes()
        elif not BIN.exists():
            sys.exit(f"tui-cast: {BIN} is not built. `make build` first.")
        else:
            capture, _ = record([str(BIN), "mira", "--addr", args.addr], KEYS)
        scenes = pick(frames(capture))
    if args.keep_raw:
        args.keep_raw.write_bytes(capture)

    out.parent.mkdir(parents=True, exist_ok=True)
    to_gif(scenes, out)
    print(f"{out}  {len(scenes)} frames  "
          f"{WIDTH}x{height_of(scenes[0][0])}  {os.path.getsize(out) / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
