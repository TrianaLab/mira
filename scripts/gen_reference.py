BEGIN = "<!-- BEGIN GENERATED: {} -->"
END = "<!-- END GENERATED: {} -->"

failures: list[str] = []


def fail(msg: str) -> None:
    failures.append(msg)


def write(rel: str, body: str) -> bool:
    # An empty body means the source could not be read and `fail` has already
    # said so. Truncating the page on top of that turns one clear error into a
    # deleted reference page nobody asked to delete.
    if not body.strip():
        return False
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text() if path.exists() else None
    if old == body:
        return False
    path.write_text(body)
    print(f"wrote {rel}")
    return True


def inject(rel: str, name: str, body: str) -> bool:
    """Replace one marked region of a hand-written page.

    Whole-file generation would cost the prose around the table, and prose is
    the half a generator cannot write: *why* a key exists, what it trades. So
    the generated part is bracketed and the rest is nobody's business but the
    author's.
    """
    path = ROOT / rel
    text = path.read_text()
    begin, end = BEGIN.format(name), END.format(name)
    if begin not in text or end not in text:
        fail(f"{rel} has no `{begin}` / `{end}` markers for the generated block.")
        return False
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    new = f"{head}{begin}\n{body}\n{end}{tail}"
    if new == text:
        return False
    path.write_text(new)
    print(f"wrote {rel} ({name})")
    return True


def cli_page() -> str:
    if not BIN.exists():
        fail(f"{BIN.relative_to(ROOT)} is not built. Run `make build` first.")
        return ""
    help_text = subprocess.run(
        [str(BIN), "--help"], capture_output=True, text=True, check=True
    ).stdout.rstrip()
    return "\n".join(
        [
            STAMP,
            "",
            "# CLI",
            "",
            "**For:** anyone starting the binary.",
            "",
            "One binary. `mira` is the server, `mira mira` is the terminal UI",
            "over the same blocks, `mira update` replaces the binary — and there",
            "is no daemon, agent or sidecar to run alongside any of them.",
            "",
            "```console",
            "$ mira --help",
            help_text,
            "```",
            # The help text above already states the precedence rule, so this
            # closing line points at the page that expands it rather than
            # saying the same sentence a second line down.
            "",
            "Every flag here is also a config-file key:",
            "[Configuration](../config.md) is the table, with the type, the",
            "default and what each one sets.",
            "",
        ]
    ).rstrip() + "\n"


def check_rustdoc_links() -> None:
    """Every `miradb.dev/api/...` link resolves to a page rustdoc actually built.

    These links are the join between the prose and the generated API docs, and
    they are the one part of it a generator cannot get right by construction: a
    renamed module or a field that becomes private leaves a 404 behind that
    nothing else notices. `target/doc` is the same tree that gets published, so
    checking against it here is checking against what the reader will get.

    Only when it is built — `make reference` is run on its own during
    development, and requiring a full rustdoc build for a table of routes would
    make the fast gate the slow one. `make site` builds it, and so does CI.
    """
    doc = ROOT / "target/doc"
    if not (doc / "mira/index.html").exists():
        print("note: target/doc is not built; skipped the rustdoc link check.")
        return
    # Every markdown file, not just the generated ones: the architecture pages
    # hand the reader off to rustdoc by module, and a rename there is exactly the
    # drift this exists to catch.
    pages = sorted(ROOT.glob("docs/**/*.md")) + [ROOT / "README.md"]
    for path in pages:
        rel = path.relative_to(ROOT)
        for url in re.findall(rf"{re.escape(RUSTDOC)}(\S+?)(?=[)\s])", path.read_text()):
            page = doc / url.split("#", 1)[0].lstrip("/")
            if not page.exists():
                fail(f"{rel} links to {url}, which rustdoc did not build.")


def main() -> int:
    changed = False
    changed |= write("docs/reference/cli.md", cli_page())
    changed |= write("docs/reference/http.md", http_page())
    changed |= inject("docs/config.md", "keys", config_table())
    changed |= inject("docs/config.md", "count", str(known_keys()))
    check_rustdoc_links()

    if failures:
        print(f"\n{len(failures)} reference check(s) failed:\n", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)
        return 1
    print("reference up to date." if not changed else "reference regenerated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
