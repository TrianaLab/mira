/// Every registered route: path -> (method, module, summary).
fn routes(f: &mut Failures) -> BTreeMap<String, (String, String, String)> {
    let mut found = BTreeMap::new();
    for path in glob(&format!("{SRC}/*.rs")) {
        let name = path.rsplit('/').next().unwrap_or(&path).to_string();
        let stem = name.trim_end_matches(".rs").to_string();
        let text = read_or_exit(&path);
        let lines: Vec<&str> = text.split('\n').collect();

        for m in route_call().captures_iter(&text) {
            let route = m[1].to_string();
            let rest = &m[2];
            let i = line_index(&text, m.get(0).expect("group 0").start());
            let (method, summary) = if let Some(h) = handler().captures(rest) {
                let fname = &h[2];
                // The handler's own doc comment, wherever it is in this file.
                let decl = re(&format!(r"(?m)^(?:async )?fn {}\b", regex::escape(fname)));
                let summary = decl
                    .find(&text)
                    .map(|m| first_paragraph(&doc_above(&lines, line_index(&text, m.start()))))
                    .unwrap_or_default();
                if summary.is_empty() {
                    f.fail(format!(
                        "{name}: handler `{fname}` for {route} has no doc comment. The \
                         reference table takes its first paragraph, and a route nobody \
                         can describe in one sentence is a route nobody should be \
                         shipping."
                    ));
                }
                (h[1].to_uppercase(), summary)
            } else {
                let Some(mac) = re(r"([a-z_]+)!\(").captures(rest) else {
                    f.fail(format!(
                        "{name}: cannot read the handler of {route}: {rest:?}"
                    ));
                    continue;
                };
                // `macro_rules! signal { ... => { post( ... ) } }`: the method is
                // the first routing constructor in the macro body.
                let body = text
                    .rsplit_once(&format!("macro_rules! {}", &mac[1]))
                    .map_or_else(|| text.clone(), |(_, tail)| tail.to_string());
                let method = re(r"\b(get|post)\(")
                    .captures(&body)
                    .map_or_else(|| "?".to_string(), |m| m[1].to_uppercase());
                let summary = comment_above(&lines, i);
                if summary.is_empty() {
                    f.fail(format!(
                        "{name}: {route} is built by a macro, so it has no doc comment. \
                         Put a `//` comment on the line above the `.route(` call; that \
                         is where this table reads it."
                    ));
                }
                (method, summary)
            };
            found.insert(route, (method, stem.clone(), summary));
        }
    }
    found
}

/// The closed key set a handler's parser enforces, found transitively.
///
/// A handler calls `parse_search`, which calls `search_doc`, which is where the
/// `known(...)` is. Following the calls is what makes this survive someone
/// moving the check one function further down. The walk order comes back too: it
/// is also where the example belongs, and guessing the parser's name from the
/// handler's only works until one of them is renamed.
fn accepted_keys(fns: &BTreeMap<String, String>, entry: &str) -> (Vec<String>, Vec<String>) {
    let known_call = re(r"(?s)known\(\s*(?:&?doc|y)\s*,\s*&\[([^\]]*)\]");
    let calls = re(r"\b([a-z_][a-z0-9_]*)\s*\(");
    let quoted = re(r#""([^"]+)""#);

    let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    let mut order = Vec::new();
    let mut queue = std::collections::VecDeque::from([entry.to_string()]);
    while let Some(fname) = queue.pop_front() {
        let Some(body) = fns.get(&fname) else {
            continue;
        };
        if !seen.insert(fname.clone()) {
            continue;
        }
        order.push(fname);
        if let Some(m) = known_call.captures(body) {
            let keys = quoted
                .captures_iter(&m[1])
                .map(|k| k[1].to_string())
                .collect();
            return (keys, order);
        }
        queue.extend(calls.captures_iter(body).map(|m| m[1].to_string()));
    }
    (Vec::new(), order)
}

/// The ```` ```yaml ```` block from the first of `names` whose doc comment has
/// one.
///
/// Read off the raw lines rather than through [`doc_above`], which strips each
/// one: the indentation inside a fenced block is the example, and a request body
/// flattened to column zero is one a reader has to re-format before it reads as
/// the nested document it is.
fn example(lines: &[&str], text: &str, names: &[String]) -> Vec<String> {
    let pat = doc_line();
    for name in names {
        let decl = re(&format!(
            r"(?m)^(?:pub(?:\([a-z:]+\))? )?(?:async )?fn {}\b",
            regex::escape(name)
        ));
        let Some(at) = decl.find(text) else { continue };
        let mut out: Vec<String> = Vec::new();
        for line in lines[..line_index(text, at.start())].iter().rev() {
            let Some(m) = pat.captures(line) else { break };
            out.push(m[1].strip_prefix(' ').unwrap_or(&m[1]).to_string());
        }
        out.reverse();
        if let Some(i) = out.iter().position(|l| l == "```yaml") {
            let end = out[i + 1..]
                .iter()
                .position(|l| l == "```")
                .map_or(out.len(), |j| i + 1 + j + 1);
            return out[i..end].to_vec();
        }
    }
    Vec::new()
}

/// `3_600_000_000_000` as the duration an operator would write.
fn nanos(literal: &str) -> String {
    let n = literal.replace('_', "").parse::<u64>().unwrap_or_default() / 1_000_000_000;
    for (unit, size) in [("d", 86400), ("h", 3600), ("m", 60)] {
        if n % size == 0 {
            return format!("{}{unit}", n / size);
        }
    }
    format!("{n}s")
}

/// Everything about a query endpoint that is not its path.
struct Detail {
    keys: Vec<String>,
    example: Vec<String>,
    field: String,
    /// Three endpoints answer "right now" to an empty body, and that is the
    /// shortest useful request against a fresh node.
    optional: bool,
}

/// Everything the "Request bodies" half of the page is made of.
struct Bodies {
    detail: BTreeMap<String, Detail>,
    /// The fields of the response `stats` object.
    stats: Vec<String>,
    /// The statuses the handlers can actually return, as (code, when).
    statuses: Vec<(&'static str, &'static str)>,
    /// The window a request with no `from` gets.
    window: String,
}

fn bodies(f: &mut Failures) -> Bodies {
    let text = read_or_exit(&format!("{SRC}/api.rs"));
    let lines: Vec<&str> = text.split('\n').collect();
    let fns = functions(&text);

    let mut detail = BTreeMap::new();
    for m in route_call().captures_iter(&text) {
        let route = m[1].to_string();
        let Some(h) = handler().captures(&m[2]) else {
            continue;
        };
        let name = h[2].to_string();
        let body = fns.get(&name).cloned().unwrap_or_default();
        let field = re(r#"run\(\s*"([a-z_]+)""#)
            .captures(&body)
            .map_or_else(|| "?".to_string(), |m| m[1].to_string());
        let (keys, chain) = accepted_keys(&fns, &name);
        if keys.is_empty() {
            f.fail(format!(
                "api.rs: cannot find the `known(...)` behind {route}, so the reference \
                 has no list of the keys it accepts."
            ));
        }
        // The parser is named after the handler often enough to be worth
        // guessing, and the example lives on whichever of the two carries it.
        let ex = example(&lines, &text, &chain);
        if ex.is_empty() {
            f.fail(format!(
                "api.rs: {route} has no ```yaml example in the doc comment of `{name}` \
                 or its parser. A list of key names is not a request body anyone can \
                 copy."
            ));
        }
        detail.insert(
            route,
            Detail {
                keys,
                example: ex,
                field,
                optional: body.contains("body.trim().is_empty()"),
            },
        );
    }

    let window = re(r#"time_field\(&doc\["from"\], now, now - ([\d_]+)\)"#).captures(&text);
    if window.is_none() {
        f.fail("api.rs: cannot read the default `from` out of `bounds`.");
    }
    let default_window = window.map_or_else(|| "?".to_string(), |m| nanos(&m[1]));

    // `envelope`'s format string, which is hand-written JSON: `\"blocks_total\":{}`.
    let stats: Vec<String> = re(r#"\\"([a-z_]+)\\":\{\}"#)
        .captures_iter(fns.get("envelope").map_or("", String::as_str))
        .map(|m| m[1].to_string())
        .collect();
    if stats.is_empty() {
        f.fail("api.rs: cannot read the fields of `stats` out of `envelope`.");
    }

    let mut seen: Vec<&str> = Vec::new();
    for path in glob(&format!("{SRC}/*.rs")) {
        let name = path.rsplit('/').next().unwrap_or(&path).to_string();
        if NOT_A_SURFACE.contains(&name.as_str()) {
            continue;
        }
        let src = read_or_exit(&path);
        let src = src
            .split_once("mod tests")
            .map_or(src.clone(), |(h, _)| h.to_string());
        for m in re(r"StatusCode::([A-Z_]+)").captures_iter(&src) {
            match STATUS.iter().find(|(code, _, _)| *code == &m[1]) {
                None => f.fail(format!(
                    "{name} returns StatusCode::{}, which the STATUS table in \
                     crates/xtask/src/reference.rs does not explain.",
                    &m[1]
                )),
                Some((code, _, _)) if !seen.contains(code) => seen.push(code),
                Some(_) => {}
            }
        }
    }
    let statuses = STATUS
        .iter()
        .filter(|(code, _, _)| seen.contains(code))
        .map(|(_, http, why)| (*http, *why))
        .collect();
    Bodies {
        detail,
        stats,
        statuses,
        window: default_window,
    }
}

/// The operators a term may use, and the columns a `field` term may name.
#[allow(
    clippy::type_complexity,
    reason = "two lists, read once, by one caller"
)]
fn where_terms(f: &mut Failures) -> (Vec<String>, Vec<(&'static str, Vec<(String, String)>)>) {
    let core = "crates/mira-core/src";
    let quoted = re(r#""([^"]+)""#);
    let ops: Vec<String> = re(r#"(?m)^\s+((?:"[a-z=!<>~]+"\s*\|?\s*)+)=> Op::"#)
        .captures_iter(&read_or_exit(&format!("{core}/query.rs")))
        .map(|arm| {
            quoted
                .captures_iter(&arm[1])
                .map(|m| format!("`{}`", &m[1]))
                .collect::<Vec<_>>()
                .join(" or ")
        })
        .collect();
    if ops.is_empty() {
        f.fail("query.rs: cannot read the operator list out of `Op::parse`.");
    }

    let text = read_or_exit(&format!("{core}/schema.rs"));
    let schemas: BTreeMap<&str, &str> = re(r"(?s)pub static (\w+): LazyLock<SchemaRef>.*?\n\}\);")
        .captures_iter(&text)
        .filter_map(|m| Some((m.get(1)?.as_str(), m.get(0).expect("group 0").as_str())))
        .collect();
    let field_new = re(r#"Field::new\(\s*"([a-z_]+)",\s*([A-Za-z:_0-9]+)"#);
    let mut out = Vec::new();
    for (signal, name) in SIGNAL_SCHEMA {
        let Some(body) = schemas.get(name) else {
            f.fail(format!(
                "schema.rs: no `{name}` schema, which is what `signal: {signal}` reads."
            ));
            continue;
        };
        let cols = field_new
            .captures_iter(body)
            .filter_map(|m| {
                let ty = COMPARABLE.iter().find(|(k, _)| *k == &m[2])?.1;
                Some((m[1].to_string(), ty.to_string()))
            })
            .collect();
        out.push((signal, cols));
    }
    (ops, out)
}

fn http_page(f: &mut Failures) -> String {
    let found = routes(f);
    let listed: Vec<&str> = GROUPS
        .iter()
        .flat_map(|(_, rs)| rs.iter().copied())
        .collect();
    for route in found.keys() {
        if !listed.contains(&route.as_str()) {
            f.fail(format!(
                "{route} is registered but not in the GROUPS table in \
                 crates/xtask/src/reference.rs. Add it to the group a reader would \
                 look under — an endpoint that exists and is not documented is the \
                 drift this exists for."
            ));
        }
    }
    for route in &listed {
        if !found.contains_key(*route) {
            f.fail(format!(
                "GROUPS lists {route}, which no router registers any more."
            ));
        }
    }
    if !f.is_empty() {
        // Every table below indexes into `found`; a missing route would panic
        // rather than print the message just collected.
        return String::new();
    }

    let mut out: Vec<String> = vec![
        STAMP.into(),
        String::new(),
        "# HTTP API".into(),
        String::new(),
        "**For:** anyone writing a client, a script or an agent against a running node.".into(),
        String::new(),
        "One port serves all of it (`listen.http`, 4318 by default). OTLP/gRPC is".into(),
        "a separate port (`listen.grpc`, 4317) and a separate protocol, so it is".into(),
        "not in this table.".into(),
        String::new(),
        "Request and response bodies are KYAML, of which JSON is a subset — so an".into(),
        "ordinary JSON client needs nothing special, and `content-type` is not".into(),
        "load-bearing.".into(),
        String::new(),
    ];

    // `main.rs` is the crate root, not a module, so its items are one level up
    // from every other file's.
    let modlink = |m: &str| {
        let tail = if m == "main" {
            "mira/index.html".to_string()
        } else {
            format!("mira/{m}/index.html")
        };
        format!("[`{m}`]({RUSTDOC}/{tail})")
    };

    // One sentence for the whole page rather than the same sentence under every
    // table: five near-identical "implementation is over there" lines read as
    // boilerplate, and a reader who wants the source wants the whole mapping at
    // once anyway.
    let mapping: Vec<String> = GROUPS
        .iter()
        .map(|(title, paths)| {
            let mods: std::collections::BTreeSet<&str> =
                paths.iter().map(|p| found[*p].1.as_str()).collect();
            format!(
                "**{title}** is {}",
                mods.into_iter()
                    .map(modlink)
                    .collect::<Vec<_>>()
                    .join(" and ")
            )
        })
        .collect();
    out.push("Each group below is a module, and its rustdoc is the reasoning behind".into());
    out.push("those routes rather than a restatement of this table:".into());
    let (last, head) = mapping.split_last().expect("GROUPS is not empty");
    out.extend(head.iter().map(|m| format!("{m};")));
    out.push(format!("{last}."));
    out.push(String::new());

    for (title, paths) in GROUPS {
        out.push(format!("## {title}"));
        out.push(String::new());
        out.push("| Endpoint | What it answers |".into());
        out.push("| --- | --- |".into());
        for p in paths {
            let (method, _, summary) = &found[*p];
            out.push(format!("| `{method} {p}` | {summary} |"));
        }
        out.push(String::new());
    }

    let Bodies {
        detail,
        stats,
        statuses,
        window,
    } = bodies(f);
    out.extend([
        "## Request bodies".into(),
        String::new(),
        "Every query endpoint takes a KYAML document and enforces a closed key".into(),
        "set: an unknown key is a 400 naming it, rather than a filter that was".into(),
        "silently not applied.".into(),
        String::new(),
        "`from` and `to` are each one of three things: `\"now\"`, a signed duration".into(),
        "relative to now (`\"-15m\"`, `\"+2h\"`), or Unix nanoseconds as a number.".into(),
        format!("Left out, the window is the last `{window}` ending now."),
        String::new(),
    ]);
    for (_, paths) in GROUPS {
        for p in paths {
            let Some(d) = detail.get(*p) else { continue };
            let (method, _, summary) = &found[*p];
            out.extend([
                format!("### `{method} {p}`"),
                String::new(),
                summary.clone(),
                String::new(),
            ]);
            out.push(format!(
                "Accepts {}.",
                d.keys
                    .iter()
                    .map(|k| format!("`{k}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
            if d.optional {
                out.push(format!(
                    "An empty body is valid, and means the last `{window}`."
                ));
            }
            out.push(String::new());
            out.push("```yaml".into());
            out.extend(d.example[1..d.example.len() - 1].iter().cloned());
            out.push("```".into());
            out.push(String::new());
            out.push(format!(
                "Answers under `{}`, with the envelope below.",
                d.field
            ));
            out.push(String::new());
        }
    }

    let (ops, schemas) = where_terms(f);
    out.extend([
        "## `where` terms".into(),
        String::new(),
        "A term names its target and its operator in two keys rather than three:".into(),
        "`{\"attr\": \"service.name\", \"eq\": \"checkout\"}`, not a `target`/`op`/`value`".into(),
        "triple. Terms in a list are ANDed; there is no `or`.".into(),
        String::new(),
        "* `attr` — an OTLP attribute key, on the record, its scope or its".into(),
        "  resource. Any key at all; nothing is declared in advance.".into(),
        "* `field` — a column of the signal itself, from the tables below.".into(),
        String::new(),
        format!("Operators: {}.", ops.join(", ")),
        String::new(),
    ]);
    for (signal, cols) in schemas {
        out.extend([
            format!("`field` names for `signal: {signal}`:"),
            String::new(),
            "| Field | Compare against |".into(),
            "| --- | --- |".into(),
        ]);
        out.extend(cols.iter().map(|(c, t)| format!("| `{c}` | {t} |")));
        out.push(String::new());
    }

    out.extend([
        "## The response envelope".into(),
        String::new(),
        "Every query answers with its own field plus one `stats` object, so a".into(),
        "caller always learns what the read cost:".into(),
        String::new(),
        "```yaml".into(),
        "{".into(),
        "  \"rows\": [ ... ],           # or series, names, frame, map, entities".into(),
        "  \"stats\": {".into(),
    ]);
    out.extend(stats.iter().map(|s| format!("    \"{s}\": 0,")));
    out.extend([
        "  },".into(),
        "  \"next\": \"...\",             # absent on the last page".into(),
        "}".into(),
        "```".into(),
        String::new(),
        "`elapsed_us` is wall time including the wait for a scan permit — the".into(),
        "number the caller actually waited. `next` is absent rather than null when".into(),
        "there is no page behind this one, so `if (doc.next)` is the whole of a".into(),
        "reader's paging logic; pass it back as `after`.".into(),
        String::new(),
        "## Status codes".into(),
        String::new(),
        "| Code | When |".into(),
        "| --- | --- |".into(),
    ]);
    out.extend(
        statuses
            .iter()
            .map(|(code, why)| format!("| `{code}` | {why} |")),
    );
    format!("{}\n", out.join("\n").trim_end())
}

