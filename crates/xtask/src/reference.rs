//! Generate the reference pages, so that nobody maintains them by hand.
//!
//! A reference page is a list of things the code already knows: the flags the
//! binary prints, the routes the router registers, the keys the config parser
//! reads. Written by hand, every one of them is a promise that decays the first
//! time someone adds a route and does not think of the docs. Nobody notices,
//! because a docs page cannot fail a test.
//!
//! So the code is the source and these pages are the output:
//!
//! ```text
//! docs/reference/cli.md    <- `mira --help`, verbatim, from the built binary
//! docs/reference/http.md   <- `.route(...)` calls + the handler's doc comment
//! docs/config.md           <- the `KNOWN` key list + `Config`'s field docs,
//!                             injected between markers so the prose survives
//! ```
//!
//! `make reference` writes them; `make reference-check` writes them and then
//! `git diff --exit-code`s, which is what CI runs. That is the same shape as the
//! committed UI bundle and the generated chart README: the artefact is in git so
//! a reader gets it without a build, and a pull request that changes the code
//! without regenerating goes red.
//!
//! Descriptions come from doc comments, which is the second half of the point:
//! rustdoc publishes the *whole* comment at miradb.dev/api/, this takes the
//! first paragraph of the same comment for the summary table, and there is one
//! text to keep true rather than two.

use std::collections::BTreeMap;
use std::process::Command;

use regex::Regex;

use crate::util::{Failures, glob, re, read_or_exit, root};

const SRC: &str = "crates/mira/src";

/// Where the rustdoc for a symbol lives once `make site` has published it. The
/// summary tables link into it, so "the rest of the comment" is one click from
/// every row rather than a file path a reader has to go and clone.
const RUSTDOC: &str = "https://miradb.dev/api";

const STAMP: &str = "<!-- Generated by `cargo run -p xtask -- reference` from the code it documents.\n     Do not edit: run `make reference`. -->";

pub fn run() -> bool {
    let mut f = Failures::default();
    let mut changed = false;
    changed |= write("docs/reference/cli.md", &cli_page(&mut f));
    changed |= write("docs/reference/http.md", &http_page(&mut f));
    changed |= inject("docs/config.md", "keys", &config_table(&mut f), &mut f);
    changed |= inject(
        "docs/config.md",
        "count",
        &known_keys(&mut f).to_string(),
        &mut f,
    );
    check_rustdoc_links(&mut f);

    if !f.report("reference check(s) failed") {
        return false;
    }
    println!(
        "{}",
        if changed {
            "reference regenerated."
        } else {
            "reference up to date."
        }
    );
    true
}

