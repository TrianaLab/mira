/// When the Rust type is ambiguous, the parser the arm calls is not.
const PARSED: [(&str, &str); 2] = [("positive", "count"), ("whole", "count")];

/// How a Rust type reads to an operator writing KYAML.
const TYPES: [(&str, &str); 8] = [
    ("String", "string"),
    ("SocketAddr", "host:port"),
    ("PathBuf", "path"),
    ("Option<PathBuf>", "path"),
    // The only optional string is `storage.offload`, and what it holds is a
    // URI. If a second one ever wants a different word, this is the line that
    // has to become a per-field override.
    ("Option<String>", "uri"),
    ("Duration", "duration"),
    ("usize", "size"),
    ("bool", "boolean"),
];

/// A Rust default expression as the operator would write it in KYAML.
fn humanize(expr: &str) -> String {
    let expr = expr.trim();
    for pattern in [
        r#"^"(.*)"(?:\.into\(\))?$"#,
        r#"^PathBuf::from\("(.*)"\)$"#,
        r#"^"(.*)"\.parse\(\)\.unwrap\(\)$"#,
    ] {
        if let Some(m) = re(pattern).captures(expr) {
            return m[1].to_string();
        }
    }
    if let Some(m) = re(r"^Duration::from_secs\(([\d\s*+]+)\)$").captures(expr) {
        // Sums of products, which is every spelling in `config.rs`
        // (`60 * 60`, `24 * 60 * 60`). Nothing here needs precedence beyond
        // that, and a real expression parser for four call sites would be the
        // tail wagging the dog.
        let secs: u64 = m[1]
            .split('+')
            .map(|term| {
                term.split('*')
                    .filter_map(|n| n.trim().parse::<u64>().ok())
                    .product::<u64>()
            })
            .sum();
        for (unit, n) in [("d", 86400), ("h", 3600), ("m", 60)] {
            if secs % n == 0 {
                return format!("{}{unit}", secs / n);
            }
        }
        return format!("{secs}s");
    }
    if let Some(m) = re(r"^(\d+) << (\d+)$").captures(expr) {
        let n: u64 = m[1].parse().unwrap_or_default();
        let shift: u32 = m[2].parse().unwrap_or_default();
        return match shift {
            10 => format!("{n}KiB"),
            20 => format!("{n}MiB"),
            30 => format!("{n}GiB"),
            _ => (n << shift).to_string(),
        };
    }
    if expr == "None" {
        return "unset".into();
    }
    expr.to_string()
}

/// `KNOWN` is the closed set the parser accepts, in the order it reads them,
/// and each key is set from exactly one `cfg.<field> = ...` a few lines below
/// its `get(&root, "<key>", env)`. Both facts come out of the same file, so the
/// table cannot list a key the binary would refuse.
fn key_setter() -> Regex {
    re(
        r#"(?m)get\(&root,\s*"([^"]+)",\s*env\)\?\s*\{\s*\n\s*cfg\.([a-z_]+)\s*=\s*\n?\s*([A-Za-z_]*)"#,
    )
}

/// How many keys the parser accepts, which is what `KNOWN` declares.
///
/// The opening sentence of `docs/config.md` counts them, and a count in prose is
/// the first thing to go stale when a key is added — this one cannot, because it
/// is the same array length the parser refuses everything else against.
fn known_keys(f: &mut Failures) -> usize {
    let text = read_or_exit(&format!("{SRC}/config.rs"));
    match re(r"const KNOWN: \[&str; (\d+)\]").captures(&text) {
        Some(m) => m[1].parse().unwrap_or_default(),
        None => {
            f.fail("config.rs: cannot find `KNOWN`'s length.");
            0
        }
    }
}

fn config_table(f: &mut Failures) -> String {
    let text = read_or_exit(&format!("{SRC}/config.rs"));
    let lines: Vec<&str> = text.split('\n').collect();
    let Some(known) = re(r"(?s)const KNOWN: \[&str; \d+\] = \[(.*?)\];").captures(&text) else {
        f.fail("config.rs: cannot find `KNOWN`, which is the list this table is.");
        return String::new();
    };
    let keys: Vec<String> = re(r#""([^"]+)""#)
        .captures_iter(&known[1])
        .map(|m| m[1].to_string())
        .collect();

    let mut setters: BTreeMap<String, String> = BTreeMap::new();
    // Three `usize` keys mean three different things, and the Rust type cannot
    // say which: `max_request_bytes` is bytes, `queue` is slots and `shards` is
    // tasks. The parser the arm calls can, so it is the one asked.
    let mut parsed: BTreeMap<String, String> = BTreeMap::new();
    for m in key_setter().captures_iter(&text) {
        setters.insert(m[1].to_string(), m[2].to_string());
        parsed.insert(m[2].to_string(), m[3].to_string());
    }

    let field = re(r"(?m)^\s{4}pub ([a-z_]+): ([^,]+),$");
    let types: BTreeMap<String, String> = field
        .captures_iter(&text)
        .map(|m| (m[1].to_string(), m[2].trim().to_string()))
        .collect();
    let defaults: BTreeMap<String, String> = re(r"(?m)^\s{12}([a-z_]+): (.+),$")
        .captures_iter(&text)
        .map(|m| (m[1].to_string(), humanize(&m[2])))
        .collect();
    let docs: BTreeMap<String, String> = field
        .captures_iter(&text)
        .map(|m| {
            let i = line_index(&text, m.get(0).expect("group 0").start());
            (m[1].to_string(), first_paragraph(&doc_above(&lines, i)))
        })
        .collect();

    // The same field, reached from the command line. `main.rs` writes one match
    // arm per flag, so the pairing is as readable here as it is to a reviewer.
    let flags: BTreeMap<String, String> = re(r#""(--[a-z-]+)" => cfg\.([a-z_]+)"#)
        .captures_iter(&read_or_exit(&format!("{SRC}/main.rs")))
        .map(|m| (m[2].to_string(), m[1].to_string()))
        .collect();

    let mut rows = vec![
        "| Key | Flag | Type | Default | What it sets |".to_string(),
        "| --- | --- | --- | --- | --- |".to_string(),
    ];
    for key in keys {
        let Some(fieldname) = setters.get(&key) else {
            f.fail(format!(
                "config.rs: `{key}` is in KNOWN but nothing assigns a field from it."
            ));
            continue;
        };
        let doc = docs.get(fieldname).cloned().unwrap_or_default();
        if doc.is_empty() {
            f.fail(format!(
                "config.rs: `Config::{fieldname}` has no doc comment, so `{key}` has \
                 nothing to say for itself in the table."
            ));
        }
        let ty = PARSED
            .iter()
            .find(|(p, _)| Some(*p) == parsed.get(fieldname).map(String::as_str))
            .map(|(_, t)| *t)
            .or_else(|| {
                let rust = types.get(fieldname)?;
                TYPES.iter().find(|(k, _)| k == rust).map(|(_, t)| *t)
            })
            .unwrap_or("?");
        rows.push(format!(
            "| [`{key}`]({RUSTDOC}/mira/config/struct.Config.html#structfield.{fieldname}) \
             | `{}` | {ty} | `{}` | {doc} |",
            flags.get(fieldname).map_or("—", String::as_str),
            defaults.get(fieldname).map_or("?", String::as_str),
        ));
    }
    rows.join("\n")
}

