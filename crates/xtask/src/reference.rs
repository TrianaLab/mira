fn write(rel: &str, body: &str) -> bool {
    // An empty body means the source could not be read and `fail` has already
    // said so. Truncating the page on top of that turns one clear error into a
    // deleted reference page nobody asked to delete.
    if body.trim().is_empty() {
        return false;
    }
    let path = root().join(rel);
    if let Some(dir) = path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    if std::fs::read_to_string(&path).is_ok_and(|old| old == body) {
        return false;
    }
    if let Err(e) = std::fs::write(&path, body) {
        eprintln!("error: {rel}: {e}");
        return false;
    }
    println!("wrote {rel}");
    true
}

/// Replace one marked region of a hand-written page.
///
/// Whole-file generation would cost the prose around the table, and prose is the
/// half a generator cannot write: *why* a key exists, what it trades. So the
/// generated part is bracketed and the rest is nobody's business but the
/// author's.
pub(crate) fn inject(rel: &str, name: &str, body: &str, f: &mut Failures) -> bool {
    if body.trim().is_empty() {
        return false;
    }
    let path = root().join(rel);
    let text = read_or_exit(rel);
    let begin = format!("<!-- BEGIN GENERATED: {name} -->");
    let end = format!("<!-- END GENERATED: {name} -->");
    let (Some((head, rest)), true) = (text.split_once(&begin), text.contains(&end)) else {
        f.fail(format!(
            "{rel} has no `{begin}` / `{end}` markers for the generated block."
        ));
        return false;
    };
    let tail = rest.split_once(&end).expect("checked above").1;
    let new = format!("{head}{begin}\n{body}\n{end}{tail}");
    if new == text {
        return false;
    }
    if let Err(e) = std::fs::write(&path, new) {
        eprintln!("error: {rel}: {e}");
        return false;
    }
    println!("wrote {rel} ({name})");
    true
}

fn cli_page(f: &mut Failures) -> String {
    let bin = root().join("target/release/mira");
    if !bin.exists() {
        f.fail("target/release/mira is not built. Run `make build` first.");
        return String::new();
    }
    let out = match Command::new(&bin).arg("--help").output() {
        Ok(out) if out.status.success() => out.stdout,
        Ok(out) => {
            f.fail(format!("`mira --help` exited {}", out.status));
            return String::new();
        }
        Err(e) => {
            f.fail(format!("`mira --help`: {e}"));
            return String::new();
        }
    };
    let help = String::from_utf8_lossy(&out).trim_end().to_string();
    let page = [
        STAMP,
        "",
        "# CLI",
        "",
        "**For:** anyone starting the binary.",
        "",
        "One binary. `mira` is the server, `mira mira` is the terminal UI",
        "over the same blocks, `mira update` replaces the binary — and there",
        "is no daemon, agent or sidecar to run alongside any of them.",
        "",
        "```console",
        "$ mira --help",
        &help,
        "```",
        // The help text above already states the precedence rule, so this
        // closing line points at the page that expands it rather than saying
        // the same sentence a second line down.
        "",
        "Every flag on the server line is also a config-file key:",
        "[Configuration](../config.md) is the table, with the type, the",
        "default and what each one sets. Four here are not, because there is",
        "nothing for them to persist: `--config` names the file itself,",
        "`--version` exits, and `--addr` and `--dry-run` belong to `mira mira`",
        "and `mira update` rather than to the server. The config file is a",
        "closed set, so writing one of them into it is an `unknown key` at",
        "boot rather than a setting that is quietly ignored.",
        "",
    ]
    .join("\n");
    format!("{}\n", page.trim_end())
}

/// Every `miradb.dev/api/...` link resolves to a page rustdoc actually built.
///
/// These links are the join between the prose and the generated API docs, and
/// they are the one part of it a generator cannot get right by construction: a
/// renamed module or a field that becomes private leaves a 404 behind that
/// nothing else notices. `target/doc` is the same tree that gets published, so
/// checking against it here is checking against what the reader will get.
///
/// Only when it is built — `make reference` is run on its own during
/// development, and requiring a full rustdoc build for a table of routes would
/// make the fast gate the slow one. `make site` builds it, and so does CI.
fn check_rustdoc_links(f: &mut Failures) {
    let doc = root().join("target/doc");
    if !doc.join("mira/index.html").exists() {
        println!("note: target/doc is not built; skipped the rustdoc link check.");
        return;
    }
    // Every markdown file, not just the generated ones: the architecture pages
    // hand the reader off to rustdoc by module, and a rename there is exactly
    // the drift this exists to catch.
    let mut pages = glob("docs/**/*.md");
    pages.push("README.md".into());
    // `[^\s)]+` rather than a lookahead for `)` or whitespace: a URL contains
    // neither, so greedy-up-to-them is the same language without needing an
    // engine that backtracks.
    let link = re(&format!(r"{}([^\s)]+)", regex::escape(RUSTDOC)));
    for rel in pages {
        let text = read_or_exit(&rel);
        for m in link.captures_iter(&text) {
            let url = &m[1];
            let page = doc.join(url.split('#').next().unwrap_or(url).trim_start_matches('/'));
            if !page.exists() {
                f.fail(format!(
                    "{rel} links to {url}, which rustdoc did not build."
                ));
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The one transformation between a Rust doc comment and a Markdown table
    /// cell. Get it wrong and every row carries a dangling reference-style link.
    #[test]
    fn a_summary_strips_intra_doc_brackets_but_not_real_links() {
        let doc = |s: &str| vec![s.to_string()];
        assert_eq!(
            first_paragraph(&doc("Set by [`Config::wal`].")),
            "Set by `Config::wal`."
        );
        assert_eq!(
            first_paragraph(&doc("See [`here`](x.md).")),
            "See [`here`](x.md)."
        );
        // Everything up to the first blank line, and no further.
        let multi = ["One".into(), "two.".into(), String::new(), "Later.".into()];
        assert_eq!(first_paragraph(&multi), "One two.");
    }

    /// `#[attr]` between the comment and the item is the case that silently
    /// produced blank table cells before it was handled.
    #[test]
    fn a_doc_comment_is_read_through_an_attribute() {
        let src = "/// What it is.\n///\n/// More.\n#[serde(skip)]\npub field: u8,\n";
        let lines: Vec<&str> = src.split('\n').collect();
        assert_eq!(
            doc_above(&lines, 4),
            vec!["What it is.".to_string(), String::new(), "More.".into()]
        );
    }

    /// Default expressions, as the operator reads them rather than as Rust.
    #[test]
    fn a_default_reads_as_the_value_an_operator_would_write() {
        for (expr, want) in [
            (r#""mira".into()"#, "mira"),
            (r#"PathBuf::from("./data")"#, "./data"),
            (r#""0.0.0.0:4318".parse().unwrap()"#, "0.0.0.0:4318"),
            ("Duration::from_secs(60)", "1m"),
            ("Duration::from_secs(24 * 60 * 60)", "1d"),
            ("Duration::from_secs(90)", "90s"),
            ("4 << 20", "4MiB"),
            ("None", "unset"),
            ("true", "true"),
        ] {
            assert_eq!(humanize(expr), want, "{expr}");
        }
    }

    #[test]
    fn a_nanosecond_literal_reads_as_a_duration() {
        assert_eq!(nanos("3_600_000_000_000"), "1h");
        assert_eq!(nanos("90_000_000_000"), "90s");
    }

    /// The generator, run against the tree it generates from. This is
    /// `make reference-check` minus the `git diff`: if the code cannot be read,
    /// it fails here rather than six minutes into CI.
    #[test]
    fn every_page_can_be_generated_from_this_tree() {
        let mut f = Failures::default();
        let http = http_page(&mut f);
        let config = config_table(&mut f);
        assert!(f.0.is_empty(), "{:?}", f.0);
        assert!(http.contains("| `POST /api/v1/query` |"), "{http}");
        assert!(config.contains("[`listen.http`]"), "{config}");
        assert!(known_keys(&mut f) > 0);
    }
}
