/// A doc comment is the run of `///` lines immediately above an item. Rust has
/// no other place to put one, so this is the whole grammar.
fn doc_line() -> Regex {
    re(r"^\s*///(.*)$")
}

/// The `///` block ending at line `i - 1`, outermost line first.
fn doc_above(lines: &[&str], i: usize) -> Vec<String> {
    let pat = doc_line();
    let mut out = Vec::new();
    for line in lines[..i].iter().rev() {
        let Some(m) = pat.captures(line) else {
            // `#[attr]` sits between the doc comment and the item it documents.
            if line.trim_start().starts_with("#[") {
                continue;
            }
            break;
        };
        out.push(m[1].trim().to_string());
    }
    out.reverse();
    out
}

/// The summary sentence: everything up to the first blank line, joined.
///
/// `[`Config::wal`]` is a rustdoc intra-doc link, and Markdown reads it as a
/// reference-style link to a definition that does not exist on the page. The
/// brackets come off; the code span stays. A `](` after it means the author
/// wrote a real link, which is left alone — hence the check on what follows
/// rather than a negative lookahead, which this regex engine does not have and
/// does not need.
fn first_paragraph(doc: &[String]) -> String {
    let joined = doc
        .iter()
        .take_while(|l| !l.is_empty())
        .cloned()
        .collect::<Vec<_>>()
        .join(" ");
    let joined = joined.trim();
    let pat = re(r"\[(`[^`]+`)\]");
    let mut out = String::with_capacity(joined.len());
    let mut last = 0;
    for m in pat.captures_iter(joined) {
        let whole = m.get(0).expect("group 0");
        if joined[whole.end()..].starts_with('(') {
            continue;
        }
        out.push_str(&joined[last..whole.start()]);
        out.push_str(&m[1]);
        last = whole.end();
    }
    out.push_str(&joined[last..]);
    out
}

/// The `//` block ending at line `i - 1`, for the routes a macro builds.
///
/// A macro expansion is not an item, so it cannot carry a doc comment and
/// rustdoc will never see it. The three OTLP export routes are the whole of that
/// case; an ordinary comment above the `.route(` line is where their description
/// lives, and the generator says so out loud rather than silently emitting a
/// blank cell.
fn comment_above(lines: &[&str], i: usize) -> String {
    let mut out: Vec<&str> = Vec::new();
    for line in lines[..i].iter().rev() {
        let t = line.trim_start();
        if !t.starts_with("//") || t.starts_with("///") {
            break;
        }
        out.push(t[2..].trim());
    }
    out.reverse();
    out.join(" ").trim().to_string()
}

/// Every free function in a file, name -> body text.
///
/// A body ends at the first line that is a bare `}`, which is true of every
/// function in this tree because rustfmt puts it there.
fn functions(text: &str) -> BTreeMap<String, String> {
    let lines: Vec<&str> = text.split('\n').collect();
    let mut out = BTreeMap::new();
    for m in fn_decl().captures_iter(text) {
        let i = line_index(text, m.get(0).expect("group 0").start());
        let mut j = i + 1;
        while j < lines.len() && lines[j] != "}" {
            j += 1;
        }
        out.insert(m[1].to_string(), lines[i..j].join("\n"));
    }
    out
}

fn fn_decl() -> Regex {
    re(r"(?m)^(?:pub(?:\([a-z:]+\))? )?(?:async )?fn ([a-z_][a-z0-9_]*)")
}

/// The 0-indexed line containing byte offset `at`.
fn line_index(text: &str, at: usize) -> usize {
    text[..at].matches('\n').count()
}

